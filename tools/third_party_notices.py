#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: every Rust crate built for the shipped targets
(Linux x86_64, Windows x86_64) and every npm package bundled into the frontend,
with its license and the license texts from the package sources.

Run from the repository root after `pnpm install`:
    python3 -I tools/third_party_notices.py
"""
import hashlib
import json
import os
import re
import subprocess
import sys

TARGETS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc"]
OWN = {"ps2-tracker", "ps2-tracker-core"}
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)([-_.].*)?$", re.I)


def run(cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def license_texts(directory):
    out = []
    try:
        names = sorted(os.listdir(directory))
    except OSError:
        return out
    for n in names:
        p = os.path.join(directory, n)
        if LICENSE_FILE.match(n) and os.path.isfile(p):
            try:
                out.append((n, open(p, encoding="utf-8", errors="replace").read().strip()))
            except OSError:
                pass
    return out


def rust_packages():
    used = set()
    for t in TARGETS:
        tree = run(["cargo", "tree", "--locked", "--target", t, "-e", "normal,build",
                    "--prefix", "none", "--format", "{p}"])
        for line in tree.splitlines():
            parts = line.split()
            if len(parts) >= 2:
                used.add((parts[0], parts[1].lstrip("v")))
    meta = json.loads(run(["cargo", "metadata", "--locked", "--format-version", "1"]))
    pkgs = []
    for p in meta["packages"]:
        if p["name"] in OWN or (p["name"], p["version"]) not in used:
            continue
        pkgs.append({
            "name": p["name"],
            "version": p["version"],
            "license": p.get("license") or "see license file",
            "source": p.get("repository") or f"https://crates.io/crates/{p['name']}",
            "texts": license_texts(os.path.dirname(p["manifest_path"])),
        })
    return pkgs


# dev dependencies whose runtime code ends up in the bundle (Svelte compiles
# components to code that imports its runtime and these helpers)
BUNDLED_DEV = {"svelte", "esm-env", "clsx"}


def npm_packages():
    data = json.loads(run(["pnpm", "licenses", "list", "--prod", "--json"]))
    dev = json.loads(run(["pnpm", "licenses", "list", "--dev", "--json"]))
    for lic, entries in dev.items():
        keep = [e for e in entries if e["name"] in BUNDLED_DEV]
        if keep:
            data.setdefault(lic, []).extend(keep)
    pkgs = []
    for lic, entries in data.items():
        for e in entries:
            for v, path in zip(e.get("versions", []), e.get("paths", [])):
                pkgs.append({
                    "name": e["name"],
                    "version": v,
                    "license": lic,
                    "source": e.get("homepage") or f"https://www.npmjs.com/package/{e['name']}",
                    "texts": license_texts(path),
                })
    return pkgs


def main():
    rust = sorted(rust_packages(), key=lambda p: (p["name"], p["version"]))
    npm = sorted(npm_packages(), key=lambda p: (p["name"], p["version"]))
    texts = {}  # hash -> (text, [package ids])
    lines = [
        "# Third-party notices",
        "",
        "PS2 Session Tracker (MIT OR Apache-2.0) includes the following third-party",
        "software. Generated by `tools/third_party_notices.py`; license texts are taken",
        "from the package sources. Packages without a license file are covered by the",
        "license named in their metadata.",
        "",
    ]
    for title, pkgs in (("Rust crates", rust), ("npm packages (bundled frontend)", npm)):
        lines += [f"## {title} ({len(pkgs)})", "", "| Package | Version | License | Source |", "|---|---|---|---|"]
        for p in pkgs:
            pid = f"{p['name']} {p['version']}"
            lines.append(f"| {p['name']} | {p['version']} | {p['license']} | {p['source']} |")
            for n, t in p["texts"]:
                h = hashlib.sha256(t.encode()).hexdigest()[:12]
                texts.setdefault(h, (n, t, []))[2].append(pid)
        lines.append("")
    lines += ["## License texts", ""]
    for h, (n, t, owners) in sorted(texts.items(), key=lambda kv: kv[1][2][0]):
        lines += [f"### {n} – used by: {', '.join(owners)}", "", "```text", t.replace("```", "'''"), "```", ""]
    open("THIRD-PARTY-NOTICES.md", "w").write("\n".join(lines))
    print(f"THIRD-PARTY-NOTICES.md: {len(rust)} crates, {len(npm)} npm packages, {len(texts)} distinct license texts")


if __name__ == "__main__":
    sys.exit(main())
